/** Every character the font can draw. */
export const PIXEL_FONT_CHARS = Object.keys(GLYPHS).join('');

export const GLYPH_WIDTH = 3;
export const GLYPH_HEIGHT = 5;
const ADVANCE = GLYPH_WIDTH + 1;

/** Width in pixels of `text` at scale 1. */
export function measurePixelText(text) {
  return Math.max(0, text.length * ADVANCE - 1);
}

/** Paint `text` (upper-cased) onto a 2D canvas context with its top-left at x, y. */
export function drawPixelText(ctx, text, x, y, color) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++) {
        if (row[gx] === '#') ctx.fillRect(cx + gx, y + gy, 1, 1);
      }
    });
    cx += ADVANCE;
  }
}
